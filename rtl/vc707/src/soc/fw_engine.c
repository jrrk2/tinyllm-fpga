/* 'w': stream a known word(i)=i*MUL pattern into DDR3 via the bridge window. */
static void cmd_ddrwrite(void) {
    print_("ddr write "); hex_(DDR_TEST_BEATS, 2); print_(" beats @0...");
    uint32_t gi = 0;
    DDR_ADDR = 0;                                  /* start byte addr (auto-advances) */
    for (uint32_t b = 0; b < DDR_TEST_BEATS; b++)
        for (uint32_t w = 0; w < 16; w++) DDR_DATA = gi++ * DDR_TEST_MUL;
    print_("done\n");
}

static uint8_t  ethf[256];        /* reply-frame scratch (headers + payload) */
static uint32_t eth_beats = 0;    /* DDR3 beats written from eth frames */
static uint32_t eth_acks  = 0;    /* replies sent (ACK/REG_RSP/ARP/ICMP) */
static const uint8_t FMAC[6] = {0x02,0x00,0x00,0x4D,0x47,0x31};  /* FPGA MAC */
static const uint8_t FIP[4]  = {FIP0, FIP1, FIP2, FIP3};         /* FPGA IP  */

static void eth_init(void) {
    ETH(ETH_MACLO) = MAC_LO;
    ETH(ETH_MACHI) = MAC_HI | (1u << 22);   /* enable; no promiscuous — ARP makes us reachable */
    ETH(ETH_RXEN)  = 31;
}

/* Copy n (mult of 4) bytes between a byte array and the RX/TX LSU window.  Each
 * 64-bit LSU word is two 32-bit halves: ETH_RX/TX(b,w) = low half (bytes w*8..+3),
 * +4 = high half.  i>>3 = word index, i&4 = the half offset. */
static void eth_rx_bytes(uint32_t b, uint8_t *d, uint32_t n) {
    for (uint32_t i = 0; i < n; i += 4) {
        uint32_t v = ETH(ETH_RX(b, i >> 3) + (i & 4));
        d[i] = v; d[i+1] = v >> 8; d[i+2] = v >> 16; d[i+3] = v >> 24;
    }
}
static void eth_tx_bytes(const uint8_t *s, uint32_t n) {   /* always TX buffer 0 */
    for (uint32_t i = 0; i < n; i += 4)
        ETH(ETH_TX(0, i >> 3) + (i & 4)) =
            s[i] | (s[i+1] << 8) | (s[i+2] << 16) | (s[i+3] << 24);
}
static void bswap(uint8_t *a, uint8_t *c, int n) { while (n--) { uint8_t t = *a; *a++ = *c; *c++ = t; } }
static uint8_t rxb(uint32_t b, uint32_t off) {     /* one frame byte from the RX buffer */
    return ETH(ETH_RX(b, off >> 3) + (off & 4)) >> ((off & 3) * 8);
}
static uint16_t cksum16(const uint8_t *p, uint32_t n) {  /* internet checksum (IP/ICMP) */
    uint32_t s = 0;
    for (uint32_t i = 0; i + 1 < n; i += 2) s += (p[i] << 8) | p[i+1];
    if (n & 1) s += p[n-1] << 8;
    while (s >> 16) s = (s & 0xFFFF) + (s >> 16);
    return ~s;
}

/* Reg-read value: serve the flow-control counters bfp_client polls from our own
 * state so its adaptive pacing auto-throttles to our drain rate (no manual -r).
 * The real backlog in the SoC is the MAC RX ring (frames the MAC queued but the
 * firmware hasn't processed) = (nextbuf - firstbuf) from RSR.  We expose that as
 * rx-done: done(0x1A)=eth_beats (processed), rx(0x19)=processed+queued, so
 * bfp_client's backlog = rx-done = ring depth -> it holds off (with -B) when we
 * fall behind.  0x18 returns the raw {lastbuf,nextbuf,firstbuf} it expects. */
static uint32_t eth_regval(uint16_t a) {
    if (a == 0x18 || a == 0x19) {
        uint32_t rsr   = ETH(ETH_RSR);
        uint32_t depth = ((rsr >> 5) - rsr) & 0x1f;   /* (nextbuf - firstbuf) & 31 */
        return (a == 0x18) ? (rsr & 0x7FFFu)          /* {lastbuf,nextbuf,firstbuf} */
                           : (eth_beats + depth);     /* rx = processed + queued */
    }
    switch (a) {
        case 0x1A: case 0x1B: return eth_beats;       /* done / ack (synchronous) */
        case 0x1C: return eth_acks;                    /* FT_ACK tx count */
        default:   return REG(a);
    }
}

/* Reply by reflecting the request headers in ethf[0..41] (swap MAC/IP/port, fix
 * lengths + IP checksum); payload pre-filled at ethf[42..].  Sent from TX buf 0. */
static void eth_reply(uint32_t plen) {
    bswap(&ethf[0],  &ethf[6],  6);   /* eth dst<->src MAC  */
    bswap(&ethf[26], &ethf[30], 4);   /* IP  src<->dst      */
    bswap(&ethf[34], &ethf[36], 2);   /* UDP src<->dst port */
    uint32_t iplen = 28 + plen, ulen = 8 + plen;
    ethf[16] = iplen >> 8; ethf[17] = iplen;   /* IP total length (BE) */
    ethf[38] = ulen >> 8;  ethf[39] = ulen;    /* UDP length (BE)      */
    ethf[40] = 0; ethf[41] = 0;                /* UDP checksum = 0     */
    ethf[24] = 0; ethf[25] = 0;
    uint16_t ck = cksum16(&ethf[14], 20);      /* IP checksum over hdr */
    ethf[24] = ck >> 8; ethf[25] = ck;
    uint32_t flen = 42 + plen;
    while (flen < 60) ethf[flen++] = 0;        /* pad to eth min frame */
    eth_tx_bytes(ethf, (flen + 3) & ~3u);
    ETH(ETH_TPLR) = flen;                       /* tbuf 0, byte_len = flen */
    eth_acks++;
}

/* ARP: reply to a who-has for our IP with "is-at FMAC". */
static void eth_arp(uint32_t b) {
    eth_rx_bytes(b, ethf, 48);                     /* eth(14)+ARP(28)=42, read 48 */
    if (ethf[20] != 0 || ethf[21] != 1) return;    /* OPER must be request (1) */
    if (ethf[38]!=FIP[0] || ethf[39]!=FIP[1] || ethf[40]!=FIP[2] || ethf[41]!=FIP[3]) return; /* TPA != us */
    for (int i = 0; i < 6; i++) { ethf[i] = ethf[22+i]; ethf[32+i] = ethf[22+i]; }   /* dst & THA = requester MAC */
    for (int i = 0; i < 4; i++)   ethf[38+i] = ethf[28+i];                           /* TPA = requester IP */
    for (int i = 0; i < 6; i++) { ethf[6+i] = FMAC[i]; ethf[22+i] = FMAC[i]; }       /* src & SHA = us */
    for (int i = 0; i < 4; i++)   ethf[28+i] = FIP[i];                               /* SPA = us */
    ethf[20] = 0; ethf[21] = 2;                    /* OPER = reply (2) */
    uint32_t flen = 42;
    while (flen < 60) ethf[flen++] = 0;
    eth_tx_bytes(ethf, (flen + 3) & ~3u);
    ETH(ETH_TPLR) = flen;
    eth_acks++;
}

/* ICMP: reply to an echo request (ping) with an echo reply. */
static void eth_icmp(uint32_t b) {
    uint32_t iptot = (rxb(b, 16) << 8) | rxb(b, 17);   /* IP total length */
    uint32_t flen  = 14 + iptot;
    if (flen > sizeof(ethf)) return;                   /* oversize ping — ignore */
    eth_rx_bytes(b, ethf, (flen + 3) & ~3u);
    if (ethf[34] != 8) return;                         /* ICMP type 8 = echo request */
    bswap(&ethf[0], &ethf[6], 6);                      /* swap eth MAC */
    bswap(&ethf[26], &ethf[30], 4);                    /* swap IP src/dst */
    ethf[34] = 0;                                       /* echo reply */
    ethf[36] = 0; ethf[37] = 0;
    uint16_t ic = cksum16(&ethf[34], iptot - 20);      /* ICMP checksum over message */
    ethf[36] = ic >> 8; ethf[37] = ic;
    ethf[24] = 0; ethf[25] = 0;
    uint16_t ip = cksum16(&ethf[14], 20);              /* IP header checksum */
    ethf[24] = ip >> 8; ethf[25] = ip;
    while (flen < 60) ethf[flen++] = 0;
    eth_tx_bytes(ethf, (flen + 3) & ~3u);
    ETH(ETH_TPLR) = flen;
    eth_acks++;
}

/* Service one RX frame: ARP who-has us -> reply; ICMP echo to us -> reply; UDP to
 * our IP:port -> the bfp_client FT_* protocol (DDR upload / regmap, with replies). */
static void eth_handle(void) {
    uint32_t rsr = ETH(ETH_RSR);
    if (!(rsr & (1u << 15))) return;
    uint32_t b = rsr & 0x1f;
    uint16_t etype = (rxb(b, 12) << 8) | rxb(b, 13);
    if (etype == ETYPE_ARP) {
        eth_arp(b);
    } else if (etype == ETYPE_IP &&
               rxb(b,30)==FIP[0] && rxb(b,31)==FIP[1] && rxb(b,32)==FIP[2] && rxb(b,33)==FIP[3]) {
        uint8_t proto = rxb(b, 23);
        if (proto == IPPROTO_ICMP) {
            eth_icmp(b);
        } else if (proto == IPPROTO_UDP && ((rxb(b,36) << 8) | rxb(b,37)) == FPGA_UDP_PORT) {
            uint32_t w5  = ETH(ETH_RX(b, 5));
            uint8_t  ft  = (w5 >> 16) & 0xFF;             /* byte 42 = frame type */
            uint8_t  seq = (w5 >> 24) & 0xFF;             /* byte 43 = seq */
            if (ft == FT_DDR_WRITE) {
                DDR_ADDR = ETH(ETH_RX(b, 5) + 4) & 0x3FFFFFFFu;   /* bytes 44-47 */
                for (uint32_t c = 0; c < 8; c++) {                /* RX words 6..13 */
                    DDR_DATA = ETH(ETH_RX(b, 6 + c));
                    DDR_DATA = ETH(ETH_RX(b, 6 + c) + 4);
                }
                eth_beats++;
                eth_rx_bytes(b, ethf, 48);
                ethf[42] = FT_ACK; ethf[43] = seq;
                eth_reply(2);
            } else if (ft == FT_DDR_WRITE_N) {
                /* Batched upload: N CONSECUTIVE 64-B chunks from byte 48, N =
                 * (UDP length - 8 - 6) / 64 (bytes 38-39, BE).  One address
                 * write — the bridge auto-advances 64 B per 16-word beat — and
                 * one ACK per frame, so the per-frame cost (header parse, ACK
                 * build + TX) is paid once per 22 chunks instead of per chunk:
                 * the single-chunk path drained only ~0.4 MB/s on this CPU. */
                uint32_t ulen = ((uint32_t)rxb(b, 38) << 8) | rxb(b, 39);
                uint32_t n    = (ulen > 14u) ? ((ulen - 14u) >> 6) : 0u;
                if (n > DDR_WRITE_N_MAX) n = DDR_WRITE_N_MAX;
                DDR_ADDR = ETH(ETH_RX(b, 5) + 4) & 0x3FFFFFFFu;   /* bytes 44-47 */
                for (uint32_t w = 6; w < 6 + 8 * n; w++) {        /* 8 RX words / chunk */
                    DDR_DATA = ETH(ETH_RX(b, w));
                    DDR_DATA = ETH(ETH_RX(b, w) + 4);
                }
                eth_beats += n;
                eth_rx_bytes(b, ethf, 48);
                ethf[42] = FT_ACK; ethf[43] = seq;
                eth_reply(2);
            } else if (ft == FT_REG_WRITE) {
                uint8_t n = ETH(ETH_RX(b, 5) + 4) & 0xFF;
                for (uint32_t i = 0; i < n; i++) {
                    uint32_t lo = ETH(ETH_RX(b, 6 + i));
                    REG((lo >> 16) & 0xFFFF) = ETH(ETH_RX(b, 6 + i) + 4);
                }
                eth_rx_bytes(b, ethf, 48);
                ethf[42] = FT_ACK; ethf[43] = seq;
                eth_reply(2);
            } else if (ft == FT_REG_READ) {
                uint32_t w5h    = ETH(ETH_RX(b, 5) + 4);
                uint16_t addr   = w5h & 0xFFFF;
                uint8_t  nwords = (w5h >> 16) & 0xFF;
                if (nwords > 19) nwords = 19;
                eth_rx_bytes(b, ethf, 48);
                ethf[42] = FT_REG_RSP; ethf[43] = seq;
                ethf[44] = addr; ethf[45] = addr >> 8;
                ethf[46] = nwords; ethf[47] = 0; ethf[48] = 0; ethf[49] = 0;
                for (uint32_t i = 0; i < nwords; i++) {
                    uint32_t v = eth_regval(addr + i);
                    ethf[50+i*4] = v; ethf[51+i*4] = v>>8; ethf[52+i*4] = v>>16; ethf[53+i*4] = v>>24;
                }
                eth_reply(8 + nwords * 4);
            } else if (ft == FT_PROG_WRITE) {
                /* {dest_word(16b), nwords(8b)} @ bytes 44-46, then code words from
                 * byte 48 — store each into progmem via the port-B 0x50 window. */
                uint32_t w5h    = ETH(ETH_RX(b, 5) + 4);
                uint16_t dest   = w5h & 0xFFFF;
                uint8_t  nwords = (w5h >> 16) & 0xFF;
                if (nwords > 16) nwords = 16;          /* 16 words (64 B) per frame */
                for (uint32_t j = 0; j < nwords; j++) {
                    uint32_t v = (j & 1) ? ETH(ETH_RX(b, 6 + (j >> 1)) + 4)
                                         : ETH(ETH_RX(b, 6 + (j >> 1)));
                    PROGW(dest + j) = v;               /* self-modify: write code word */
                }
                eth_rx_bytes(b, ethf, 48);
                ethf[42] = FT_ACK; ethf[43] = seq;
                eth_reply(2);
            } else if (ft == FT_PROG_EXEC) {
                /* {entry_word(16b)} @ bytes 44-45 — call the loaded overlay as a
                 * leaf function and return its 32-bit result in the ACK. */
                uint16_t entry = ETH(ETH_RX(b, 5) + 4) & 0xFFFF;
                eth_rx_bytes(b, ethf, 48);             /* capture reply headers first */
                uint32_t (*fn)(void) = (uint32_t (*)(void))(PROG_BASE + ((uint32_t)entry << 2));
                uint32_t r = fn();
                ethf[42] = FT_ACK; ethf[43] = seq;
                ethf[44] = r; ethf[45] = r >> 8; ethf[46] = r >> 16; ethf[47] = r >> 24;
                eth_reply(6);
            }
        }
    }
    ETH(ETH_RSR) = (b + 1) & 0x1f;                    /* free the buffer */
}

static void cmd_eth(void) {
    print_("eth beats="); hex_(eth_beats, 8);
    print_(" acks=");      hex_(eth_acks, 8); putc_('\n');
}


/* ======================= serial prompt mode =======================
 * Type a line of text (2+ chars) + Enter on the console: the firmware
 * tokenises it (greedy longest match against the vocabulary table the host
 * uploaded to DDR3), loads the prompt ROM, restarts the engine, waits for
 * done and prints the generated continuation.  Single-char lines are the
 * debug menu commands.
 *
 * DDR3 read window (picosoc_eth_bridge 0x32/0x33 -> soc_ddr_bridge): a load
 * from DDR_RD_DATA performs one 32-bit DDR3 read at DDR_RD_ADDR (stalls the
 * CPU ~0.4 us) and advances the address by 4.  Only used while the engine
 * is idle (stray SoC beats are dropped by the idle engine consumers).
 *
 * Vocabulary table (host/gen_serial_vocab.py, uploaded with
 * `bfp_client -a 0x3C000000 upload generated/serial_vocab.bin`):
 *   u32[0] 'SVOC'  [1] n_tokens  [2] order_off  [3] entries_off  [4] blob_off
 *   byte 32: first-byte index, 256 x {u32 start, u32 count} into `order`
 *   order:   u16 token ids grouped by first byte, longest token first
 *   entries: u32 per token id = (len << 24) | blob_off
 *   blob:    raw token bytes (same blob as bfp_vocab.bin)                */
#define DDR_RD_DATA (*(volatile uint32_t *)0x32000000u)
#define DDR_RD_ADDR (*(volatile uint32_t *)0x33000000u)
#define SVOC_BASE   0x3C000000u   /* 960 MiB: above the 843 MB smollm360 image */
#define SVOC_MAGIC  0x434F5653u   /* 'SVOC' little-endian */
#define NPROMPT_MAX 24            /* LBFP_FULL_NPROMPT_MAX (prompt ROM depth) */
#define N_GEN       8             /* LBFP_FULL_NGEN */
#define LINE_MAX    160

static uint32_t rd32(uint32_t a) { DDR_RD_ADDR = a; return DDR_RD_DATA; }
static uint32_t rd8_wa = 0xFFFFFFFFu, rd8_w;        /* one-word cache for byte reads */
static uint8_t  rd8(uint32_t a) {
    uint32_t wa = a & ~3u;
    if (wa != rd8_wa) { rd8_wa = wa; rd8_w = rd32(wa); }
    return (uint8_t)(rd8_w >> (8u * (a & 3u)));
}
static void dec_(uint32_t v) {
    char b[11]; int i = 10; b[i] = 0;
    do { b[--i] = (char)('0' + v % 10u); v /= 10u; } while (v);
    print_(b + i);
}

static uint32_t sv_order, sv_entries, sv_blob;
static int      sv_ok;
static int sv_init(void) {
    rd8_wa = 0xFFFFFFFFu;
    if (rd32(SVOC_BASE) != SVOC_MAGIC) { sv_ok = 0; return 0; }
    sv_order   = SVOC_BASE + rd32(SVOC_BASE + 8);
    sv_entries = SVOC_BASE + rd32(SVOC_BASE + 12);
    sv_blob    = SVOC_BASE + rd32(SVOC_BASE + 16);
    sv_ok = 1; return 1;
}
static void print_tok(uint32_t t) {
    uint32_t e = rd32(sv_entries + t * 4u), len = e >> 24, off = e & 0xFFFFFFu;
    for (uint32_t i = 0; i < len; i++) putc_((char)rd8(sv_blob + off + i));
}
/* Greedy longest match: for each position scan the first-byte group (sorted
 * longest-first), take the first token whose bytes all match.  Byte-level BPE
 * has a token for every single byte, so this always advances. */
static int tokenize(const char *s, int n, uint16_t *out) {
    int pos = 0, cnt = 0;
    while (pos < n && cnt < NPROMPT_MAX) {
        uint32_t ix = SVOC_BASE + 32u + (uint32_t)(uint8_t)s[pos] * 8u;
        uint32_t start = rd32(ix), count = rd32(ix + 4u);
        uint32_t best = 0; int best_len = 0;
        for (uint32_t i = start; i < start + count; i++) {
            uint32_t ow  = rd32(sv_order + (i & ~1u) * 2u);
            uint32_t tok = (i & 1u) ? (ow >> 16) : (ow & 0xFFFFu);
            uint32_t e   = rd32(sv_entries + tok * 4u);
            int len = (int)(e >> 24); uint32_t off = e & 0xFFFFFFu;
            if (len > n - pos) continue;
            int k = 0;
            while (k < len && (uint8_t)s[pos + k] == rd8(sv_blob + off + (uint32_t)k)) k++;
            if (k == len) { best = tok; best_len = len; break; }
        }
        if (best_len == 0) { pos++; continue; }
        out[cnt++] = (uint16_t)best; pos += best_len;
    }
    return cnt;
}
static void run_prompt(const char *line, int n) {
    if (!sv_ok && !sv_init()) {
        print_("no vocab table at 0x3C000000 (host: bfp_client -a 0x3C000000 upload serial_vocab.bin)\n");
        return;
    }
    uint16_t toks[NPROMPT_MAX];
    int nt = tokenize(line, n, toks);
    if (nt == 0) return;
    print_("tokens:");
    for (int i = 0; i < nt; i++) { putc_(' '); dec_(toks[i]); }
    putc_('\n');
    for (int i = 0; i < nt; i++) {               /* prompt ROM = BRAM kind 6 */
        REG(R_BRAM_TARGET) = (6u << 18) | (uint32_t)i;
        REG(R_BRAM_DATA)   = toks[i];
    }
    REG(R_N_PROMPT) = (uint32_t)nt;
    REG(R_RESTART)  = 1;
    for (volatile int d = 0; d < 20000; d++);    /* let the latched done clear (CDC) */
    uint32_t polls = 0;
    while (!(REG(R_LAYER_DONE) & 2u)) {
        for (volatile int d = 0; d < 100; d++);
        if (++polls > 4000000u) { print_("engine timeout\n"); return; }
    }
    print_(line);
    for (int k = nt - 1; k < nt + N_GEN; k++) {  /* prediction at the last prompt pos + N_GEN more */
        uint32_t w = REG(R_RESULT + (k >> 1));
        uint32_t t = (k & 1) ? (w >> 16) : (w & 0xFFFFu);
        if (t == 0) break;                       /* <|endoftext|> */
        print_tok(t);
    }
    putc_('\n');
}

void main(void)
{
    reg_uart_clkdiv = UART_DIV;
    print_("\n=== PicoSoC engine console ===\n");
    cmd_version();
    eth_init();
    menu();
    print_("> ");
    static char line[LINE_MAX];
    int ll = 0;
    for (;;) {
        eth_handle();                 /* service one eth RX frame (weight upload) */
        int32_t c = reg_uart_data;
        if (c == -1) continue;
        char ch = (char)c;
        if (ch == 0x7f || ch == 0x08) { if (ll) { ll--; print_("\b \b"); } continue; }
        if (ch != '\r' && ch != '\n') {
            if (ll < LINE_MAX - 1) { line[ll++] = ch; putc_(ch); }
            continue;
        }
        putc_('\n');
        if (ll == 1) {
            switch (line[0]) {
                case 'v': cmd_version(); break;
                case 'c': cmd_crc();     break;
                case 's': cmd_status();  break;
                case 'w': cmd_ddrwrite();break;
                case 'e': cmd_eth();     break;
                case 'r': cmd_restart(); break;
                case '?':
                case 'h': menu();        break;
                default:  print_("? press ? for menu\n");
            }
        } else if (ll > 1) {
            line[ll] = 0;
            run_prompt(line, ll);
        }
        ll = 0;
        print_("> ");
    }
}
